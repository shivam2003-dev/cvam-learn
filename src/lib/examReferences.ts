/** Official references for a question, or a sensible default for its section. */
export function referencesFor(question: ExamQuestion): Reference[] {
  const own = (question as ExamQuestion & { references?: { title: string; url: string }[] }).references;
  if (own && own.length > 0) {
    return own.map((ref) => ({ type: "official", ...ref }));
  }
  return byId[question.id] ?? bySection[question.section] ?? [R.waf];
}
